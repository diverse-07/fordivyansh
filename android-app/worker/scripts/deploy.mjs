import { spawnSync } from "node:child_process";
import {
  mkdtempSync,
  readFileSync,
  writeFileSync,
  renameSync,
  rmSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { deploymentUrl } from "./deployment-url.mjs";

const workerDirectory = fileURLToPath(new URL("../", import.meta.url));
const temporaryDirectory = mkdtempSync(join(tmpdir(), "librevision-deploy-"));
const outputFile = join(temporaryDirectory, "deployment.ndjson");
const args = process.argv.slice(2);
try {
  const result = spawnSync(
    process.execPath,
    [
      join(workerDirectory, "node_modules/wrangler/bin/wrangler.js"),
      "deploy",
      ...args,
    ],
    {
      cwd: workerDirectory,
      stdio: "inherit",
      env: { ...process.env, WRANGLER_OUTPUT_FILE_PATH: outputFile },
    },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) process.exitCode = result.status ?? 1;
  else if (!args.includes("--dry-run")) {
    const url = deploymentUrl(readFileSync(outputFile, "utf8"));
    const config = fileURLToPath(
      new URL("../../gateway.properties", import.meta.url),
    );
    writeFileSync(
      config + ".tmp",
      `# Public Worker origin; generated by worker/scripts/deploy.mjs. No secrets.\nmuseGatewayUrl=${url}\n`,
    );
    renameSync(config + ".tmp", config);
    console.log(
      `Android gateway set to ${url}. Build the APK from the project root; users need no gateway setup.`,
    );
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}
