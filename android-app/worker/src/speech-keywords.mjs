// The live voice API rejects individual keyword hints longer than 30 characters.
function pack(name) {
  const result = [];
  let phrase = "";
  for (const word of name.split(/\s+/)) {
    if (word.length > 30) continue;
    if (phrase && phrase.length + 1 + word.length > 30) {
      result.push(phrase);
      phrase = word;
    } else phrase = phrase ? phrase + " " + word : word;
  }
  if (phrase) result.push(phrase);
  return result;
}
export const speechKeywords = [...new Set(reviewedKeywords.flatMap(pack))];
